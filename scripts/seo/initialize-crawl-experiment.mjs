#!/usr/bin/env node
import crypto from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'
import {
  DEFAULT_SEED,
  addDaysIso,
  assignArms,
  normalizeExperimentPath,
  parseCsv,
  stableHash,
  stableStringify,
  toCsv,
  validateAssignedRows,
} from './crawl-experiment-core.mjs'
import { refreshGoogleCrawlerRanges } from './refresh-google-crawler-ranges.mjs'

const ROOT = process.cwd()
const OPS_DIR = path.join(ROOT, 'ops', 'seo', 'crawl-experiment')
const INPUT = process.argv.find((arg) => arg.startsWith('--input='))?.split('=')[1] || path.join(OPS_DIR, 'eligible-urls.csv')
const SEED = process.argv.find((arg) => arg.startsWith('--seed='))?.split('=')[1] || DEFAULT_SEED
const START_ARG = process.argv.find((arg) => arg.startsWith('--freeze-start='))?.split('=')[1]
const EXPERIMENT_ID = 'crawl-indexing-rct-v1'
const SITE = 'https://thehippiescientist.net'

async function readJsonOptional(file) {
  try { return JSON.parse(await fs.readFile(file, 'utf8')) } catch { return null }
}

function slugFromPathname(pathname) {
  return pathname.split('/').filter(Boolean)[1]
}

async function sourceHashFor(pathname) {
  const slug = slugFromPathname(pathname)
  const candidates = [
    ['herbs', path.join(ROOT, 'public/data/herbs.json')],
    ['herbs-summary', path.join(ROOT, 'public/data/herbs-summary.json')],
    ['summary-index', path.join(ROOT, 'public/data/summary-indexes/herbs-summary.json')],
    ['detail', path.join(ROOT, `public/data/herbs-detail/${slug}.json`)],
  ]
  const layers = {}
  for (const [name, file] of candidates) {
    const parsed = await readJsonOptional(file)
    if (Array.isArray(parsed)) {
      const match = parsed.find((row) => row && typeof row === 'object' && row.slug === slug)
      if (match) layers[name] = match
    } else if (parsed && typeof parsed === 'object') {
      if (parsed.slug === slug || name === 'detail') layers[name] = parsed
    }
  }
  if (!Object.keys(layers).length) throw new Error(`No source data found for ${pathname}`)
  return stableHash(stableStringify(layers))
}

function unescapeXml(text) {
  return text.replaceAll('&amp;', '&').replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&quot;', '"').replaceAll('&apos;', "'")
}

async function fetchSitemapLastmods(url = `${SITE}/sitemap.xml`, seen = new Set()) {
  if (seen.has(url) || seen.size > 25) return new Map()
  seen.add(url)
  const response = await fetch(url, { headers: { accept: 'application/xml,text/xml;q=0.9,*/*;q=0.1' } })
  if (!response.ok) throw new Error(`Sitemap fetch failed (${response.status}): ${url}`)
  const xml = await response.text()
  const output = new Map()
  for (const [, block] of xml.matchAll(/<url>([\s\S]*?)<\/url>/gi)) {
    const loc = block.match(/<loc>([\s\S]*?)<\/loc>/i)?.[1]?.trim()
    const lastmod = block.match(/<lastmod>([\s\S]*?)<\/lastmod>/i)?.[1]?.trim()
    if (loc && lastmod) output.set(normalizeExperimentPath(unescapeXml(loc)), lastmod)
  }
  const childLocs = [...xml.matchAll(/<sitemap>[\s\S]*?<loc>([\s\S]*?)<\/loc>[\s\S]*?<\/sitemap>/gi)].map((match) => unescapeXml(match[1].trim()))
  for (const child of childLocs) {
    const nested = await fetchSitemapLastmods(child, seen)
    for (const [key, value] of nested) output.set(key, value)
  }
  return output
}

function edgeRegistryModule(manifest) {
  const registry = Object.fromEntries(manifest.rows.map((row) => [row.pathname, {
    pathname: row.pathname,
    arm: row.arm,
    lastmod_block: row.lastmod_block,
    baseline_last_crawled: row.baseline_last_crawled,
    baseline_lastmod: row.baseline_lastmod,
  }]))
  return `// Generated by scripts/seo/initialize-crawl-experiment.mjs; do not hand-edit.\n` +
    `export const CRAWL_EXPERIMENT_ACTIVE = true\n` +
    `export const CRAWL_EXPERIMENT_ID = ${JSON.stringify(manifest.experiment_id)}\n` +
    `export const CRAWL_EXPERIMENT_REGISTRY = Object.freeze(${JSON.stringify(registry, null, 2)})\n`
}

async function main() {
  const inputRows = parseCsv(await fs.readFile(INPUT, 'utf8'))
  if (!inputRows.every((row) => row.baseline_last_crawled)) {
    throw new Error('Every one of the 97 eligible rows must include baseline_last_crawled; refusing to invent baseline crawl data')
  }

  const sitemapLastmods = await fetchSitemapLastmods()
  const assigned = assignArms(inputRows.map((row) => ({ ...row, pathname: normalizeExperimentPath(row.pathname || row.url) })), SEED)
  const freezeStart = new Date(START_ARG || Date.now()).toISOString()
  const freezeEnd = addDaysIso(freezeStart, 28)
  const rows = []

  for (const row of assigned) {
    const baselineLastmod = row.baseline_lastmod || sitemapLastmods.get(row.pathname)
    if (!baselineLastmod) throw new Error(`No live sitemap lastmod found for ${row.pathname}`)
    const frozen = row.arm === 'treatment' || row.arm === 'control'
    rows.push({
      pathname: row.pathname,
      url: `${SITE}${row.pathname}`,
      arm: row.arm,
      randomization_key: row.randomization_key,
      baseline_last_crawled: row.baseline_last_crawled,
      baseline_lastmod: baselineLastmod,
      baseline_source_hash: await sourceHashFor(row.pathname),
      baseline_canonical: `${SITE}${row.pathname}`,
      baseline_indexability: 'index',
      lastmod_block: frozen ? `${EXPERIMENT_ID}:${freezeStart}:${freezeEnd}` : null,
      request_indexing_requested_at: null,
    })
  }
  validateAssignedRows(rows)

  const manifest = {
    schema_version: 1,
    experiment_id: EXPERIMENT_ID,
    status: 'active',
    seed: SEED,
    generated_at: new Date().toISOString(),
    freeze_start: freezeStart,
    freeze_end: freezeEnd,
    design: { treatment: 20, control: 20, observational: 57, treatment_action: 'manual-gsc-url-inspection-request-indexing' },
    rows: rows.sort((a, b) => a.pathname.localeCompare(b.pathname)),
  }

  await fs.mkdir(OPS_DIR, { recursive: true })
  await fs.writeFile(path.join(OPS_DIR, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
  await fs.writeFile(path.join(OPS_DIR, 'request-indexing-checklist.csv'), toCsv(manifest.rows.filter((row) => row.arm === 'treatment'), [
    'url', 'pathname', 'baseline_last_crawled', 'baseline_lastmod', 'request_indexing_requested_at',
  ]))
  await fs.writeFile(path.join(ROOT, 'functions/_shared/crawl-experiment-registry.mjs'), edgeRegistryModule(manifest))
  const ranges = await refreshGoogleCrawlerRanges({ root: ROOT, write: true })
  const manifestSha = crypto.createHash('sha256').update(stableStringify(manifest)).digest('hex')
  console.log(`Initialized ${EXPERIMENT_ID}: 20 treatment / 20 control / 57 observational; freeze ends ${freezeEnd}`)
  console.log(`Manifest SHA-256: ${manifestSha}`)
  console.log(`Google common-crawler CIDRs captured: ${ranges.prefixes.length} (${ranges.creationTime})`)
  console.log('Treatment remains manual in Search Console; this tool does not misuse the Indexing API.')
}

main().catch((error) => { console.error(error); process.exit(1) })
