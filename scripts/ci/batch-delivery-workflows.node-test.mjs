import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const load = x => readFileSync(x, 'utf8')

test('postdeploy retirement is independent from protected main and requires exact success', () => {
  const action = load('.github/workflows/retire-completed-workstream.yml')
  const script = load('scripts/ci/retire-completed-workstream.mjs')
  assert.match(action, /workflow_run:/)
  assert.match(action, /workflows: \["Deploy to Cloudflare Pages"\]/)
  assert.match(action, /branches: \[main\]/)
  assert.match(action, /workflow_run\.conclusion == 'success'/)
  assert.match(action, /workflow_run\.head_branch == 'main'/)
  assert.match(action, /persist-credentials: false/)
  assert.match(action, /contents: write/)
  assert.match(action, /pull-requests: write/)
  assert.match(script, /deployed\.conclusion !== 'success'/)
  assert.match(script, /deployed\.head_sha !== sha/)
  assert.match(script, /deployed\.head_branch !== 'main'/)
  assert.match(script, /issue\.state !== 'closed'/)
  assert.match(script, /root\.tree\?\.sha/)
  assert.match(script, /api\('POST', 'git\/trees'/)
  assert.match(script, /api\('POST', 'git\/commits'/)
  assert.match(script, /api\('POST', 'git\/refs'/)
  assert.match(script, /api\('POST', 'pulls'/)
  assert.doesNotMatch(script, /api\('PATCH', 'git\/refs\/heads\/main'/)
  assert.doesNotMatch(script, /api\('PUT', 'contents\/'/)
})

test('optional source-scoped batch validation cannot replace release gates', () => {
  const action = load('.github/workflows/batch-preflight.yml')
  const script = load('scripts/dev/batch-preflight.mjs')
  const ci = load('.github/workflows/ci.yml')
  assert.match(action, /workflow_dispatch:/)
  assert.doesNotMatch(action, /^\s+pull_request:/m)
  assert.match(action, /contents: read/)
  assert.match(action, /--mode="\$BATCH_MODE"/)
  assert.match(action, /--receipt=tmp\/batch-preflight-receipt\.json/)
  assert.match(script, /releaseAuthorized: false/)
  assert.match(script, /planBatch/)
  assert.match(script, /classifyReleaseImpact/)
  assert.match(script, /vitest','related'/)
  assert.match(script, /npm','run','typecheck'/)
  assert.match(script, /validate:claim-discipline/)
  assert.match(script, /audit:high/)
  assert.match(ci, /Run full tests \(vitest \+ a11y gate\)/)
  assert.match(ci, /npm run build:deploy/)
  assert.match(ci, /Verify build output/)
})
