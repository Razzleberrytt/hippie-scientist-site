import fs from 'node:fs'
import path from 'node:path'
import { normalizeText } from './normalize.mjs'
import { repoRoot } from './paths.mjs'

/**
 * Duplicate-organism audit.
 *
 * Two entities that carry the same `latin_name` describe the same organism.
 * Sometimes that is deliberate — a plant part or preparation split out as its
 * own profile (`roselle-seed` alongside `hibiscus-sabdariffa`) — and sometimes
 * it is a genuine duplicate that grew from a slug/common-name pair
 * (`allium-sativum` alongside `garlic`).
 *
 * The distinction the audit *can* make mechanically is how many of them the
 * site actually serves. Two live profiles for one organism is a
 * duplicate-content problem whether or not the split was intentional, so those
 * are reported separately and are the ones worth a human pass first.
 *
 * Liveness comes from the route manifest and `public/_redirects`, never from
 * `runtime_export_decision` — see `routedSlugs` for why.
 *
 * This never proposes a fix: entity identity, slugs, and publishing controls are
 * all prohibited to the enrichment pipeline by contract.
 */

const PUBLIC_EXPORTS = new Set(['full_public_runtime', 'primary_runtime_priority'])

/**
 * Slugs whose route is 301'd away at the edge.
 *
 * `runtime_export_decision` is not a reliable signal of what the site actually
 * publishes: a redirected entity keeps `full_public_runtime` in the workbook
 * while the build emits no page for it and the sitemap omits it. Reading the
 * column alone overstated the duplicate count by nearly 2x — 22 groups rather
 * than the 13 that genuinely compete — so the audit reads `public/_redirects`,
 * which is the authority for what a URL actually does.
 */
export function redirectedSlugs({ redirectsPath = path.join(repoRoot, 'public/_redirects') } = {}) {
  const map = new Map()
  if (!fs.existsSync(redirectsPath)) return map
  for (const line of fs.readFileSync(redirectsPath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const match = trimmed.match(/^\/(herbs|compounds)\/([a-z0-9-]+)\/?\s+(\S+)\s+30[12]/)
    if (match) map.set(match[2], match[3])
  }
  return map
}

/**
 * Slugs the site actually emits a route for.
 *
 * `public/data/runtime-manifests/route-manifest.json` is generated by the build
 * and committed, so it is available without a build and is what the exporter
 * actually walks. Checked against `out/sitemap.xml` it agrees on 11 of 12
 * contested entities, which is close enough to treat as the liveness signal;
 * the workbook column is not, since a redirected entity keeps
 * `full_public_runtime` while emitting nothing.
 */
export function routedSlugs({ manifestPath = path.join(repoRoot, 'public/data/runtime-manifests/route-manifest.json') } = {}) {
  if (!fs.existsSync(manifestPath)) return null
  try {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
    const slugs = new Set()
    for (const entry of Array.isArray(manifest) ? manifest : []) {
      const match = String(entry?.route ?? '').match(/^\/(?:herbs|compounds)\/([a-z0-9-]+)\/?$/)
      if (match) slugs.add(match[1])
    }
    return slugs.size ? slugs : null
  } catch {
    return null
  }
}

export function auditDuplicateOrganisms(canonical, { field = 'latin_name', redirects = null, routes = undefined } = {}) {
  const redirectMap = redirects ?? redirectedSlugs()
  const routeSet = routes === undefined ? routedSlugs() : routes
  const byValue = new Map()

  for (const [slug, { row }] of canonical.bySlug) {
    const value = normalizeText(row[field]).toLowerCase()
    if (!value) continue
    if (!byValue.has(value)) byValue.set(value, [])
    const redirectsTo = redirectMap.get(slug) || null
    byValue.get(value).push({
      slug,
      name: normalizeText(row.name),
      value: normalizeText(row[field]),
      runtime_export_decision: normalizeText(row.runtime_export_decision),
      seo_indexing_recommendation: normalizeText(row.seo_indexing_recommendation),
      redirects_to: redirectsTo,
      // Live means the site actually serves a page here: a route is emitted for
      // it AND the edge does not redirect that route away. Falls back to the
      // workbook column only when no route manifest is available.
      published: (routeSet ? routeSet.has(slug) : PUBLIC_EXPORTS.has(normalizeText(row.runtime_export_decision))) && !redirectsTo,
      workbook_published: PUBLIC_EXPORTS.has(normalizeText(row.runtime_export_decision)),
    })
  }

  const groups = [...byValue.entries()]
    .filter(([, entities]) => entities.length > 1)
    .map(([value, entities]) => {
      const sorted = [...entities].sort((a, b) => a.slug.localeCompare(b.slug))
      const publishedCount = sorted.filter((e) => e.published).length
      const workbookCount = sorted.filter((e) => e.workbook_published).length
      return {
        value: sorted[0].value,
        key: value,
        entities: sorted,
        entity_count: sorted.length,
        published_count: publishedCount,
        workbook_published_count: workbookCount,
        severity:
          publishedCount > 1
            ? 'live-duplicate'
            : workbookCount > 1
              ? 'already-redirected'
              : 'single-published',
      }
    })
    .sort(
      (a, b) =>
        b.published_count - a.published_count ||
        b.entity_count - a.entity_count ||
        a.key.localeCompare(b.key),
    )

  return {
    audit_version: 1,
    field,
    liveness_source: routeSet ? 'route-manifest' : 'workbook-column',
    distinct_values: byValue.size,
    shared_values: groups.length,
    live_duplicates: groups.filter((g) => g.severity === 'live-duplicate').length,
    already_redirected: groups.filter((g) => g.severity === 'already-redirected').length,
    workbook_published_duplicates: groups.filter((g) => g.workbook_published_count > 1).length,
    groups,
  }
}

export function formatDuplicateAudit(report) {
  const lines = []
  lines.push(`${report.field}: ${report.distinct_values} distinct value(s)`)
  lines.push(`  held by more than one entity          ${report.shared_values}`)
  lines.push(`  with 2+ profiles actually served       ${report.live_duplicates}`)
  lines.push(`  already resolved by a 301 redirect    ${report.already_redirected}`)
  lines.push(`  (workbook column alone would say       ${report.workbook_published_duplicates})`)
  lines.push(`  liveness source                       ${report.liveness_source}`)
  if (!report.groups.length) return lines.join('\n')

  lines.push('')
  for (const group of report.groups) {
    const flag =
      group.severity === 'live-duplicate'
        ? `LIVE x${group.published_count}   `
        : group.severity === 'already-redirected'
          ? 'redirected   '
          : '             '
    lines.push(`${flag}  ${group.value}`)
    for (const entity of group.entities) {
      lines.push(
        `             ${entity.slug.padEnd(28)} ${entity.name.padEnd(30)} ${entity.runtime_export_decision}` +
          (entity.redirects_to ? `  -> 301 ${entity.redirects_to}` : ''),
      )
    }
  }
  lines.push('')
  lines.push('Entity identity and publishing controls are prohibited to the enrichment pipeline.')
  lines.push('Resolving these is a human editorial decision: merge, or redirect one slug to the other.')
  return lines.join('\n')
}
